"""도움말 관련 MCP 도구"""


async def get_help(topic: str = "") -> str:
    """
    게임 도움말을 확인합니다.

    Args:
        topic: 도움말 주제 (비우면 전체 목록)

    Returns:
        도움말 내용
    """
    topics = {
        "commands": _help_commands,
        "combat": _help_combat,
        "skills": _help_skills,
        "items": _help_items,
        "classes": _help_classes,
        "status": _help_status,
        "dungeon": _help_dungeon,
    }

    if not topic:
        return """
═══════════════════════════════════════════════════
  📖 도움말
═══════════════════════════════════════════════════

  사용법: get_help [주제]

  [주제 목록]
  • commands - 사용 가능한 명령어
  • combat - 전투 시스템
  • skills - 스킬 시스템
  • items - 아이템 시스템
  • classes - 직업 안내
  • status - 상태 이상
  • dungeon - 던전 구조

  예시: get_help combat

═══════════════════════════════════════════════════
"""

    topic_lower = topic.lower()
    if topic_lower in topics:
        return topics[topic_lower]()

    return f"❌ 알 수 없는 주제: {topic}\n   'get_help'로 주제 목록을 확인하세요."


def _help_commands() -> str:
    return """
═══════════════════════════════════════════════════
  📖 명령어 목록
═══════════════════════════════════════════════════

  [게임 진행]
  • start_game - 세이브 확인 (이어하기/새 게임 선택)
  • start_game [이름] - 해당 이름으로 새 게임 시작
  • get_status - 현재 상태 확인
  • move [방향] - 이동 (north/south/east/west)
  • interact - 현재 방과 상호작용 (선택지 표시)
  • interact [번호] - 선택지 선택 (예: interact 2)
  • get_map - 미니맵 확인

  [전투]
  • attack - 기본 공격
  • use_skill [스킬ID] - 스킬 사용
  • defend - 방어 (데미지 50% 감소)
  • flee - 도망 (보스전 불가)
  • get_skills - 스킬 목록

  [아이템]
  • get_inventory - 인벤토리 확인
  • use_item [아이템ID] - 아이템 사용
  • equip [아이템ID] - 장비 장착
  • unequip [슬롯] - 장비 해제

  [상점]
  • shop_list - 상점 목록
  • buy [아이템ID] - 구매
  • sell [아이템ID] - 판매

═══════════════════════════════════════════════════
"""


def _help_combat() -> str:
    return """
═══════════════════════════════════════════════════
  📖 전투 시스템
═══════════════════════════════════════════════════

  [전투 흐름]
  1. 적과 조우 시 자동으로 전투 시작
  2. 플레이어 → 적 순서로 행동
  3. 적 HP가 0이 되면 승리
  4. 플레이어 HP가 0이 되면 게임 오버

  [데미지 계산]
  • 기본: ATK - DEF (최소 1)
  • 크리티컬: 기본 × 1.5 (확률 15%)
  • 스킬: 기본 × 스킬 배율 + 추가 효과

  [행동]
  • 공격: 기본 데미지
  • 스킬: MP 소모, 강력한 효과
  • 방어: 받는 데미지 50% 감소
  • 도망: 30~80% 확률 (보스전 불가)

  [보스전]
  • 1~4층: 50% 확률, 5층: 100% 보스 등장
  • 보스전에서는 도망 불가
  • 페이즈별 패턴 변화

═══════════════════════════════════════════════════
"""


